#!/usr/bin/env python3
"""Generate the C23 identifier and NFC tables from the Unicode 15.1 UCD."""

import argparse
from hashlib import sha256
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'dev/src/support/unicode/identifier_data.inc'
LOW_LIMIT = 0x800
PAGE_SIZE = 256
INPUT_SHA256 = {
    'DerivedCoreProperties.txt': 'f55d0db69123431a7317868725b1fcbf1eab6b265d756d1bd7f0f6d9f9ee108b',
    'DerivedNormalizationProps.txt': '8875dccee2bc1a7c1fe568a3b502a9e78c9e0495afd96b6568b4294d0ed1f7e1',
    'UnicodeData.txt': '2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86',
}


def read_ucd(directory, name):
    data = (directory / name).read_bytes()
    if sha256(data).hexdigest() != INPUT_SHA256[name]:
        raise ValueError(f'{name} does not match Unicode 15.1.0')
    return data.decode('utf-8')


def properties(text):
    for line in text.splitlines():
        fields = [field.strip() for field in line.partition('#')[0].split(';')]
        if len(fields) >= 2:
            limits = fields[0].split('..')
            yield range(int(limits[0], 16), int(limits[-1], 16) + 1), fields[1:]


def read_properties(directory):
    flags = bytearray(0x110000)
    combining_classes = bytearray(0x110000)
    for points, (name, *_) in properties(read_ucd(directory, 'DerivedCoreProperties.txt')):
        bits = {'XID_Start': 1, 'XID_Continue': 2}.get(name)
        if bits is not None:
            for point in points:
                flags[point] |= bits
    exclusions = set()
    for points, (name, *values) in properties(read_ucd(directory, 'DerivedNormalizationProps.txt')):
        if name == 'NFC_QC':
            bits = {'N': 4, 'M': 8}[values[0]]
            for point in points:
                flags[point] |= bits
        elif name == 'Full_Composition_Exclusion':
            exclusions.update(points)
    decompositions = {}
    for row in read_ucd(directory, 'UnicodeData.txt').splitlines():
        code, name, _, combining_class, _, decomposition, *_ = row.split(';')
        point = int(code, 16)
        combining_classes[point] = int(combining_class)
        if name.endswith((', First>', ', Last>')) and combining_classes[point] != 0:
            raise ValueError(f'unexpected combining-class range {name}')
        if decomposition and not decomposition.startswith('<'):
            parts = tuple(int(value, 16) for value in decomposition.split())
            if len(parts) == 1:
                decompositions[point] = (parts[0], 0)
            elif len(parts) == 2:
                decompositions[point] = parts
            else:
                raise ValueError(f'unexpected canonical decomposition of {name}')
            flags[point] |= 16
            # Unicode 15.1 has no retained canonical decomposition among
            # nonstarters or Maybe characters. These follow the NFC starter
            # and can be checked or copied without looking up a decomposition.
            if (combining_classes[point] or flags[point] & 8) and not flags[point] & 4:
                raise ValueError(f'{name} needs canonical decomposition after the NFC starter')
    for point in range(0xAC00, 0xD7A4):
        flags[point] |= 16
    compositions = {parts: point for point, parts in decompositions.items() if point not in exclusions}
    if any(second == 0 for _, second in compositions):
        raise ValueError('unexpected singleton canonical composition')
    return flags, combining_classes, decompositions, compositions


def ranges(combining_classes, flags):
    first = LOW_LIMIT
    previous = combining_classes[first], flags[first]
    for point in range(first + 1, len(flags)):
        value = combining_classes[point], flags[point]
        if value == previous:
            continue
        if any(previous):
            yield first, point - 1, *previous
        first, previous = point, value
    if any(previous):
        yield first, len(flags) - 1, *previous


def page_starts(intervals):
    at = 0
    end = intervals[-1][1] // PAGE_SIZE + 1
    for page in range(LOW_LIMIT // PAGE_SIZE, end + 1):
        while at < len(intervals) and intervals[at][1] < page * PAGE_SIZE:
            at += 1
        yield str(at)


def packed_entry(first, second, third):
    packed = (first << 42) | (second << 21) | third
    return f'0x{packed:016X}ULL'


def table(name, element, entries, columns):
    values = list(entries)
    yield f'constexpr {element} {name}[] = {{'
    for i in range(0, len(values), columns):
        yield '\t' + ', '.join(values[i:i + columns]) + ','
    yield '};'


def generate(directory):
    flags, combining_classes, decompositions, compositions = read_properties(directory)
    intervals = list(ranges(combining_classes, flags))
    lines = [
        '// Generated by scripts/generate_unicode_identifier_data.py from the Unicode 15.1.0 UCD.',
        '// Copyright 1991-2023 Unicode, Inc. See LICENSE-UNICODE.txt in this directory.',
        '',
        '#pragma once',
        '',
        '#include <cstdint>',
        '',
        'namespace unicode {',
        'namespace {',
        '',
        'struct PropertyRange',
        '{',
        '\tchar32_t first;',
        '\tchar32_t last;',
        '\tuint8_t combining_class;',
        '\tuint8_t flags;',
        '};',
        '',
        *table('kLowProperties', 'uint16_t',
               (f'0x{(combining_classes[point] << 8 | flags[point]):04X}' for point in range(0x80, LOW_LIMIT)), 10),
        '',
        *table('kProperties', 'PropertyRange',
               (f'{{0x{first:X}, 0x{last:X}, {klass}, {bits}}}' for first, last, klass, bits in intervals), 3),
        '',
        *table('kPageStarts', 'uint16_t', page_starts(intervals), 14),
        '',
        *table('kDecompositions', 'uint64_t',
               (packed_entry(code, *parts) for code, parts in sorted(decompositions.items())), 4),
        '',
        *table('kCompositions', 'uint64_t',
               (packed_entry(*parts, code) for parts, code in sorted(compositions.items())), 4),
        '',
        '} // namespace',
        '} // namespace unicode',
        '',
    ]
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('ucd', type=Path, help='directory of extracted Unicode 15.1.0 files')
    parser.add_argument('--check', action='store_true', help='verify the checked-in data')
    args = parser.parse_args()
    contents = generate(args.ucd)
    if args.check:
        if OUTPUT.read_text() != contents:
            parser.exit(1, 'Unicode identifier data is out of date\n')
    else:
        OUTPUT.write_text(contents)


if __name__ == '__main__':
    main()
